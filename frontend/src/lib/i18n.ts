export type TranslationKey = keyof typeof en;

export const translations: Record<PlatformLanguage, Record<TranslationKey, string>> = {
  en,
  rw,
  fr,
};

export function translate(
  language: PlatformLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  let text = translations[language][key] ?? translations.en[key] ?? key;
  if (params) {
    for (const [param, value] of Object.entries(params)) {
      text = text.replace(`{${param}}`, String(value));
    }
  }
  return text;
}

export function isPlatformLanguage(value: string | null): value is PlatformLanguage {
  return value === "en" || value === "rw" || value === "fr";
}

type TranslateFn = (key: TranslationKey, params?: Record<string, string | number>) => string;

export function translateRole(
  role: "admin" | "employee" | "user",
  t: TranslateFn,
): string {
  if (role === "admin") return t("role.admin");
  if (role === "employee") return t("role.employee");
  return t("role.citizen");
}
